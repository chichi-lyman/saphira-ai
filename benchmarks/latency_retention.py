"""Reproducible local routing/content-ID microbenchmark; not a pgvector benchmark."""
from __future__ import annotations
import json, platform, statistics, sys, time
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from core.sovereign_oracle.audit import deterministic_memory_id

def route(task: dict[str, str]) -> str:
    return {"read": "memory", "write": "ledger", "deploy": "approval"}.get(task.get("kind", ""), "general")

def main() -> None:
    iterations = 100_000
    samples = []
    for i in range(iterations):
        task = {"kind": ("read", "write", "deploy", "other")[i % 4]}
        start = time.perf_counter_ns()
        route(task)
        samples.append(time.perf_counter_ns() - start)
    median_us = statistics.median(samples) / 1000
    p95_us = sorted(samples)[int(len(samples) * .95)] / 1000
    count = 10_000
    ids = [deterministic_memory_id("bench-v1", {"transaction": i, "state": f"state-{i}"}) for i in range(count)]
    retained = sum(deterministic_memory_id("bench-v1", {"transaction": i, "state": f"state-{i}"}) == ids[i] for i in range(count))
    result = {"benchmark": "local deterministic route and content-addressed IDs",
        "environment": {"python": sys.version, "platform": platform.platform()},
        "routing": {"iterations": iterations, "median_us": median_us, "p95_us": p95_us,
                    "median_under_0_05ms": median_us < 50},
        "memory_identity": {"transactions": count, "retention": retained / count,
                            "method": "SHA-256 canonical JSON; not vector retrieval"},
        "limitations": ["single local run", "no pgvector/database/network measurement",
                        "not publication-grade evidence"]}
    (ROOT / "BENCHMARK_RESULTS.json").write_text(json.dumps(result, indent=2) + "\n")
    md = ["# Benchmark Results", "", "Generated by the benchmark script.", "",
        "| Metric | Result |", "|---|---:|", f"| Route samples | {iterations:,} |",
        f"| Median route latency | {median_us:.3f} µs |", f"| p95 route latency | {p95_us:.3f} µs |",
        f"| Median under 0.05 ms target | {median_us < 50} |", f"| State IDs | {count:,} |",
        f"| Deterministic identity retention | {retained/count:.4%} |", "",
        "This measures local dispatch and content-addressed IDs, not pgvector retrieval accuracy or production latency."]
    (ROOT / "BENCHMARK_RESULTS.md").write_text("\n".join(md) + "\n")
    tex = "\\begin{tabular}{lr}\nMetric & Result \\\\\nMedian route (\\mu s) & " + f"{median_us:.3f}" + " \\\\\np95 route (\\mu s) & " + f"{p95_us:.3f}" + " \\\\\nIdentity retention & " + f"{retained/count:.4%}" + " \\\\\n\\end{tabular}\n"
    (ROOT / "benchmarks" / "latency_retention.tex").write_text(tex)
    print(json.dumps(result, indent=2))
if __name__ == "__main__":
    main()
